-- Enterprise AI Risk-Based Testing (RBT) Platform
-- Multi-Tenant Snowflake DDL (PDH Production Ready)

CREATE DATABASE IF NOT EXISTS IF_SUPPLY_CHAIN;
CREATE SCHEMA IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE;
CREATE SCHEMA IF NOT EXISTS IF_SUPPLY_CHAIN.FAILURES_TRANSIENT DATA_RETENTION_TIME_IN_DAYS = 7;

-- 1. Multi-Tenant Team Registry (Isolated Compute & Orchestrator Auth)
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAMS (
    TEAM_ID STRING PRIMARY KEY,
    TEAM_NAME STRING NOT NULL,
    SNOWFLAKE_DATABASE STRING NOT NULL,
    SNOWFLAKE_WAREHOUSE STRING NOT NULL,     -- Isolated compute warehouse per tenant (e.g., 'PDH_RBT_WH')
    DEFAULT_DOWNSTREAM_TARGET STRING,        -- Free-text tag (e.g., 'ERP_PDH_SUPPLY_PLANNING_SRC_BASE', 'PLANNING_SOLVER', 'FINANCE_MART')
    ORCHESTRATOR_API_KEY_HASH STRING,        -- SHA-256 hash for X-API-Key service-to-service gate triggers
    ALERT_WEBHOOK_URL STRING,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 2. Multi-Tenant User Role Mapping (RBAC)
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAM_MEMBERS (
    MEMBER_ID STRING PRIMARY KEY,
    TEAM_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAMS(TEAM_ID),
    USER_EMAIL STRING NOT NULL,
    USER_ROLE STRING NOT NULL,               -- 'AUTHOR' | 'APPROVER' | 'ADMIN'
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 3. Onboarded Datasets / Data Areas per Team (PDH Temporal & Hierarchy Aware)
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_DOMAIN_REGISTRY (
    DOMAIN_ID STRING PRIMARY KEY,
    TEAM_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAMS(TEAM_ID),
    DOMAIN_NAME STRING NOT NULL,             -- Friendly name (e.g., 'Intersite BOM', 'Demand Netting', 'GL Journal')
    TARGET_SCHEMA STRING NOT NULL,
    TARGET_TABLE STRING NOT NULL,
    RELATED_TABLES VARIANT,                  -- JSON array of parent/reference tables for FK checks
    TEMPORAL_CYCLE_COLUMN STRING,            -- Optional column for cycle filtering (e.g., 'PLANNING_CYCLE_ID')
    SNAPSHOT_TS_COLUMN STRING,               -- Optional column for snapshot filtering (e.g., 'SNAPSHOT_TS')
    MAX_HIERARCHY_DEPTH INT DEFAULT 10,      -- Guardrail to prevent infinite recursion in BOM hierarchy checks
    DOWNSTREAM_CONSUMER STRING,              -- Specific downstream system consuming this dataset
    BUSINESS_CONTEXT STRING,                 -- Plain-English description of business rules & failure impacts
    CRITICALITY STRING DEFAULT 'HIGH',       -- 'CRITICAL', 'HIGH', 'MEDIUM'
    BASELINE_SCHEMA_JSON VARIANT,            -- Step-0 Schema Contract baseline snapshot
    UPSTREAM_SOURCE_TABLE STRING,            -- Optional upstream staging/source table for reconciliation
    TRANSFORMATION_SQL STRING,               -- Optional pipeline transformation SQL for lineage-aware discovery
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    CREATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 4. Risk-Based Test Rules (AI-Generated & Human-Approved)
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEST_RULES (
    RULE_ID STRING PRIMARY KEY,
    TEAM_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAMS(TEAM_ID),
    DOMAIN_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_DOMAIN_REGISTRY(DOMAIN_ID),
    RISK_NAME STRING NOT NULL,
    RISK_CATEGORY STRING,                    -- 'REFERENTIAL_INTEGRITY', 'HIERARCHY_LOOP', 'BOUNDARY_VALUE', 'DUPLICATE_KEY', 'FRESHNESS_ANOMALY', 'FROZEN_HORIZON_VIOLATION', 'SCHEMA_CONTRACT_DRIFT', 'PIPELINE_RECONCILIATION', 'REGRESSION_DIFF'
    RISK_PRIORITY STRING NOT NULL,           -- 'P1_BLOCKER', 'P2_WARNING', 'P3_INFO'
    LIKELIHOOD_SPDH_SUPPLY_PLANNING_SRC_BASE INT DEFAULT 3,          -- Quantitative likelihood (1-5)
    IMPACT_SPDH_SUPPLY_PLANNING_SRC_BASE INT DEFAULT 3,              -- Quantitative impact (1-5)
    RISK_SPDH_SUPPLY_PLANNING_SRC_BASE INT DEFAULT 9,                -- LIKELIHOOD_SPDH_SUPPLY_PLANNING_SRC_BASE * IMPACT_SPDH_SUPPLY_PLANNING_SRC_BASE (1-25)
    BUSINESS_IMPACT_DESC STRING,
    VALIDATION_SQL STRING NOT NULL,          -- Must return failing rows (0 rows = PASS); supports :planning_cycle_id
    STATUS STRING DEFAULT 'DRAFT',           -- 'DRAFT', 'DRAFT_NEEDS_REVIEW', 'APPROVED', 'ARCHIVED'
    LAST_COMPILE_ERROR STRING,               -- Populated if auto-debug loop exhausts MAX_RETRIES = 3
    IS_SHARED_TEMPLATE BOOLEAN DEFAULT FALSE,
    CREATED_BY STRING,
    APPROVED_BY STRING,
    UPDATED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 5. Audit Trail & Rule History Versioning Table
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEST_RULE_HISTORY (
    HISTORY_ID STRING PRIMARY KEY,
    RULE_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEST_RULES(RULE_ID),
    VERSION_NUM INT NOT NULL,
    STATUS_OLD STRING,
    STATUS_NEW STRING,
    VALIDATION_SQL_OLD STRING,
    VALIDATION_SQL_NEW STRING,
    MODIFIED_BY STRING NOT NULL,
    MODIFIED_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- 6. Execution Runs, Async Status, Break-Glass Override & AI Triage Log
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_EXECUTION_RUNS (
    RUN_ID STRING PRIMARY KEY,
    TEAM_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEAMS(TEAM_ID),
    DOMAIN_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_DOMAIN_REGISTRY(DOMAIN_ID),
    TRIGGERED_BY STRING,                     -- 'ORCHESTRATOR_API', 'CI_CD', 'MANUAL_UI'
    EXECUTION_STATUS STRING DEFAULT 'RUNNING', -- 'RUNNING', 'COMPLETED', 'FAILED', 'TIMED_OUT'
    PLANNING_CYCLE_ID STRING,                -- Runtime cycle filter (e.g., 'WEEK_42_POR')
    SNAPSHOT_TS TIMESTAMP_NTZ,               -- Runtime snapshot filter
    GATE_DECISION STRING,                    -- 'PENDING', 'PASS', 'BLOCKED_DOWNSTREAM', 'PASS_WITH_WARNINGS', 'OVERRIDDEN_PASS'
    TOTAL_RULES_RUN INT DEFAULT 0,
    P1_FAILURES INT DEFAULT 0,
    P2_FAILURES INT DEFAULT 0,
    ENVIRONMENT STRING DEFAULT 'PROD',       -- 'DEV' | 'UAT' | 'PROD'
    TARGET_SCHEMA_OVERRIDE STRING,           -- Optional schema/table override for CI/CD PR or UAT runs
    COVERAGE_PCT FLOAT,                      -- Critical column test coverage % (0-100)
    RELEASE_CONFIDENCE_SPDH_SUPPLY_PLANNING_SRC_BASE FLOAT,          -- Composite Release Confidence SPDH_SUPPLY_PLANNING_SRC_BASE (0-100)
    SCHEMA_DRIFT_STATUS STRING DEFAULT 'PASS', -- Step-0 Schema Contract status ('PASS' | 'DRIFT_DETECTED' | 'SKIPPED')
    SCHEMA_DRIFT_DETAILS VARIANT,            -- JSON details of any dropped/narrowed columns
    AI_TRIAGE_SUMMARY STRING,
    OVERRIDE_BY STRING,                      -- Populated only on emergency Break-Glass override by APPROVER/ADMIN
    OVERRIDE_REASON STRING,                  -- Mandatory justification for audit compliance
    OVERRIDE_TS TIMESTAMP_NTZ,
    RUN_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    COMPLETED_TS TIMESTAMP_NTZ
);

-- 7. Per-Rule Execution Details & Transient Failure Table Reference
CREATE TABLE IF NOT EXISTS IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_EXECUTION_DETAILS (
    DETAIL_ID STRING PRIMARY KEY,
    RUN_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_EXECUTION_RUNS(RUN_ID),
    RULE_ID STRING REFERENCES IF_SUPPLY_CHAIN.PDH_SUPPLY_PLANNING_SRC_BASE.RBT_TEST_RULES(RULE_ID),
    RISK_NAME STRING,
    RISK_PRIORITY STRING,
    RULE_RUN_STATUS STRING,                  -- 'PASS', 'FAIL', 'ERROR', 'TIMEOUT'
    FAILED_ROW_COUNT INT,
    SAMPLE_FAILING_KEYS VARIANT,             -- Top 5 failing rows as JSON
    FAILURE_TABLE_REF STRING,                -- Optional transient table (e.g., 'IF_SUPPLY_CHAIN.FAILURES_TRANSIENT.FAIL_{DETAIL_ID}')
    ERROR_MESSAGE STRING,
    EXECUTION_MS INT
);
